    $('#q-svg').addEventListener('click', () => {
      if (!currentQR) return;
      U.downloadText(svgMarkup(currentQR, state.size), 'vistanology-qr-' + state.type + '.svg', 'image/svg+xml');
      toast(t('qr.svg'), 'success');
    });

    renderForm();
    updatePreview();
