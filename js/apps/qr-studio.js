  const TYPES = [
    ['url', 'link'], ['text', 'text'], ['email', 'mail'], ['phone', 'phone'],
    ['sms', 'message'], ['wifi', 'wifi'], ['vcard', 'contact']
  ];

  const state = {
    type: 'url',
    url: { value: '' },
    text: { value: '' },
    email: { to: '', subject: '', body: '' },
    phone: { value: '' },
    sms: { number: '', message: '' },
    wifi: { ssid: '', password: '', security: 'WPA', hidden: false },
    vcard: { first: '', last: '', phone: '', email: '', org: '', url: '' },
    fg: '#0A1B2E', bg: '#FFFFFF', size: 512, margin: 4, ecc: 'M',
    logo: null, logoImg: null
  };

  let currentQR = null;
  let alive = false;

  const wifiEsc = (s) => String(s).replace(/([\\;," :])/g, '\\$1');

  function buildPayload() {
    const ty = state.type;
    const v = state[ty];
    /* "empty" is not "wrong". A blank field is the starting state of the tool, and it was
       being returned as an error: the stage showed a red sentence with role="alert" before
       the user had typed anything, and every keystroke re-announced it. The caller paints a
       placeholder for empty and keeps the alert for malformed input. */
    const isEmpty = (s) => !String(s).trim();
    if (ty === 'url') {
      let raw = v.value.trim();
      if (!raw) return { empty: true };
      if (!/^[a-z][a-z0-9+.-]*:/i.test(raw)) raw = 'https://' + raw;
      try {
        const u = new URL(raw);
        if (!['http:', 'https:'].includes(u.protocol)) return { error: t('qr.err.proto') };
        if (!/^(localhost|(\d{1,3}\.){3}\d{1,3}|([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,})$/i.test(u.hostname)) return { error: t('qr.err.urlbad') };
        return { payload: u.href };
      } catch { return { error: t('qr.err.urlbad') }; }
    }
    if (ty === 'text') {
      if (isEmpty(v.value)) return { empty: true };
      return { payload: v.value };
    }
    if (ty === 'email') {
      if (isEmpty(v.to)) return { empty: true };
      if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v.to.trim())) return { error: t('qr.err.email') };
      const params = [];
      if (v.subject) params.push('subject=' + encodeURIComponent(v.subject));
      if (v.body) params.push('body=' + encodeURIComponent(v.body));
      return { payload: 'mailto:' + v.to.trim() + (params.length ? '?' + params.join('&') : '') };
    }
    if (ty === 'phone') {
      const n = v.value.replace(/[\s\-()]/g, '');
      if (!n) return { empty: true };
      if (!/^\+?[0-9]{3,15}$/.test(n)) return { error: t('qr.err.phone') };
      return { payload: 'tel:' + n };
    }
    if (ty === 'sms') {
      const n = v.number.replace(/[\s\-()]/g, '');
      if (!n) return { empty: true };
      if (!/^\+?[0-9]{3,15}$/.test(n)) return { error: t('qr.err.sms') };
      return { payload: 'SMSTO:' + n + ':' + v.message };
    }
    if (ty === 'wifi') {
      if (isEmpty(v.ssid)) return { empty: true };
      if (v.security !== 'nopass' && !v.password) return { error: t('qr.err.wifipass') };
      return { payload: 'WIFI:T:' + v.security + ';S:' + wifiEsc(v.ssid) + ';P:' + wifiEsc(v.password) + ';H:' + (v.hidden ? 'true' : 'false') + ';;' };
    }
    if (ty === 'vcard') {
      if (isEmpty(v.first) && isEmpty(v.last)) return { empty: true };
      const lines = ['BEGIN:VCARD', 'VERSION:3.0', 'N:' + v.last + ';' + v.first + ';;;', 'FN:' + (v.first + ' ' + v.last).trim()];
      if (v.phone) lines.push('TEL;TYPE=CELL:' + v.phone);
      if (v.email) lines.push('EMAIL:' + v.email);
      if (v.org) lines.push('ORG:' + v.org);
      if (v.url) lines.push('URL:' + v.url);
      lines.push('END:VCARD');
      return { payload: lines.join('\n') };
    }
    return { empty: true };
  }

  function drawQR(canvas, qr, size, withLogo) {
    const count = qr.getModuleCount();
    const total = count + state.margin * 2;
    const cell = Math.max(1, Math.floor(size / total));
    const dim = cell * total;
    canvas.width = dim;
    canvas.height = dim;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = state.bg;
    ctx.fillRect(0, 0, dim, dim);
    ctx.fillStyle = state.fg;
    for (let r = 0; r < count; r++) {
      for (let c = 0; c < count; c++) {
        if (qr.isDark(r, c)) ctx.fillRect((c + state.margin) * cell, (r + state.margin) * cell, cell, cell);
      }
    }
    if (withLogo && state.logoImg) {
      const logoDim = Math.floor(dim * 0.2);
      const pad = Math.max(2, Math.floor(cell * 0.8));
      const x = Math.floor((dim - logoDim) / 2), y = Math.floor((dim - logoDim) / 2);
      ctx.fillStyle = state.bg;
      ctx.fillRect(x - pad, y - pad, logoDim + pad * 2, logoDim + pad * 2);
      ctx.drawImage(state.logoImg, x, y, logoDim, logoDim);
    }
  }

  function svgMarkup(qr, size) {
    const count = qr.getModuleCount();
    const total = count + state.margin * 2;
    let path = '';
    for (let r = 0; r < count; r++) {
      for (let c = 0; c < count; c++) {
        if (qr.isDark(r, c)) path += 'M' + (c + state.margin) + ' ' + (r + state.margin) + 'h1v1h-1z';
      }
    }
    let logo = '';
    if (state.logo && state.logoImg) {
      const dim = total * 0.2;
      const pad = total * 0.02;
      const x = (total - dim) / 2, y = (total - dim) / 2;
      logo = '<rect x="' + (x - pad) + '" y="' + (y - pad) + '" width="' + (dim + pad * 2) + '" height="' + (dim + pad * 2) + '" fill="' + state.bg + '"/>' +
        '<image href="' + state.logo + '" x="' + x + '" y="' + y + '" width="' + dim + '" height="' + dim + '" preserveAspectRatio="xMidYMid meet"/>';
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 ' + total + ' ' + total + '" shape-rendering="crispEdges">' +
      '<rect width="' + total + '" height="' + total + '" fill="' + state.bg + '"/>' +
      '<path d="' + path + '" fill="' + state.fg + '"/>' + logo + '</svg>';
  }

  function updatePreview() {
    if (!alive) return;
    const errEl = $('#q-error');
    const canvas = $('#q-canvas');
    const emptyEl = $('#q-empty');
    const { payload, error, empty } = buildPayload();
    const showEmpty = (on) => { emptyEl.hidden = !on; canvas.hidden = on; };
    if (empty) {
      currentQR = null;
      errEl.textContent = '';
      showEmpty(true);
      $('#q-meta').textContent = '';
      $('#q-png').disabled = true;
      $('#q-svg').disabled = true;
      return;
    }
    if (error) {
      currentQR = null;
      errEl.textContent = error;
      showEmpty(false);
      canvas.style.opacity = '.22';
      $('#q-meta').textContent = '';
      $('#q-png').disabled = true;
      $('#q-svg').disabled = true;
      return;
    }
    try {
      const qr = qrcode(0, state.ecc);
      qr.addData(payload);
      qr.make();
      currentQR = qr;
      errEl.textContent = '';
      showEmpty(false);
      canvas.style.opacity = '1';
      drawQR(canvas, qr, 300, true);
      $('#q-png').disabled = false;
      $('#q-svg').disabled = false;
      $('#q-meta').textContent = t('qr.modules', { n: qr.getModuleCount(), e: state.ecc });
    } catch {
      currentQR = null;
      errEl.textContent = t('qr.err.long');
      showEmpty(false);
      $('#q-png').disabled = true;
      $('#q-svg').disabled = true;
    }
  }

  const schedulePreview = U.debounce(updatePreview, 160);

  function renderForm() {
    const ty = state.type;
    const v = state[ty];
    const field = (id, label, type, value, extra = '') =>
      '<div class="field"><label for="q-f-' + id + '">' + label + '</label><input id="q-f-' + id + '" class="input" type="' + type + '" value="' + esc(value) + '" ' + extra + '></div>';
    let html = '';
    if (ty === 'url') html = field('value', t('qr.f.url'), 'url', v.value, 'placeholder="https://example.com"');
    if (ty === 'text') html = '<div class="field"><label for="q-f-value">' + t('qr.f.text') + '</label><textarea id="q-f-value" class="input" rows="4">' + esc(v.value) + '</textarea></div>';
    if (ty === 'email') html = field('to', t('qr.f.to'), 'email', v.to, 'placeholder="name@example.com"') + field('subject', t('qr.f.subject'), 'text', v.subject) + '<div class="field"><label for="q-f-body">' + t('qr.f.body') + '</label><textarea id="q-f-body" class="input" rows="3">' + esc(v.body) + '</textarea></div>';
    if (ty === 'phone') html = field('value', t('qr.f.phone'), 'tel', v.value, 'placeholder="+55 11 91234-5678"');
    if (ty === 'sms') html = field('number', t('qr.f.number'), 'tel', v.number, 'placeholder="+55 11 91234-5678"') + '<div class="field"><label for="q-f-message">' + t('qr.f.message') + '</label><textarea id="q-f-message" class="input" rows="3">' + esc(v.message) + '</textarea></div>';
    if (ty === 'wifi') html =
      field('ssid', t('qr.f.ssid'), 'text', v.ssid) +
      '<div class="field"><label for="q-f-security">' + t('qr.f.security') + '</label><select id="q-f-security" class="input"><option value="WPA">' + t('qr.f.sec.wpa') + '</option><option value="WEP">' + t('qr.f.sec.wep') + '</option><option value="nopass">' + t('qr.f.sec.open') + '</option></select></div>' +
      field('password', t('qr.f.password'), 'text', v.password) +
      '<label class="check-row"><input type="checkbox" id="q-f-hidden"' + (v.hidden ? ' checked' : '') + '> ' + t('qr.f.hidden') + '</label>';
    if (ty === 'vcard') html =
      '<div class="field-row">' + field('first', t('qr.f.first'), 'text', v.first) + field('last', t('qr.f.last'), 'text', v.last) + '</div>' +
      '<div class="field-row">' + field('phone', t('qr.f.phone'), 'tel', v.phone) + field('email', t('qr.type.email'), 'email', v.email) + '</div>' +
      '<div class="field-row">' + field('org', t('qr.f.org'), 'text', v.org) + field('url', t('qr.f.website'), 'url', v.url) + '</div>';

    const form = $('#q-form');
    form.innerHTML = html;
    if (ty === 'wifi') $('#q-f-security', form).value = v.security;

    $$('input, textarea, select', form).forEach((inp) => {
      inp.addEventListener('input', () => {
        const key = inp.id.replace('q-f-', '');
        state[ty][key] = inp.type === 'checkbox' ? inp.checked : inp.value;
        schedulePreview();
      });
    });
  }

  async function setLogo(file) {
    if (!file) return;
    if (!file.type.startsWith('image/')) { toast(t('qr.logo.bad'), 'error'); return; }
    try {
      const url = await U.readFileAsDataURL(file);
      const img = await U.loadImage(url);
      state.logo = url;
      state.logoImg = img;
      state.ecc = 'H';
      $('#q-ecc').value = 'H';
      $('#q-ecc').disabled = true;
      $('#q-logo-remove').hidden = false;
      $('#q-logo-hint').hidden = false;
      toast(t('qr.logo.added'), 'success');
      updatePreview();
    } catch { toast(t('qr.logo.readfail'), 'error'); }
  }

